#!/bin/sh
# Writes the initial Prisma migration straight from schema.prisma. Needs no database.
# Run once (locally or via: docker compose run --rm --no-deps backend sh scripts/gen-initial-migration.sh)
# and commit prisma/migrations. Later schema changes: `npx prisma migrate dev --name <change>`.
set -eu
cd "$(dirname "$0")/.."

if [ -d prisma/migrations ] && [ -n "$(ls -A prisma/migrations 2>/dev/null)" ]; then
  echo "prisma/migrations already exists; nothing to do." >&2
  exit 0
fi

dir="prisma/migrations/$(date -u +%Y%m%d%H%M%S)_init"
mkdir -p "$dir"
npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.prisma --script > "$dir/migration.sql"
printf '# Please do not edit this file manually\n# It should be added in your version-control system (i.e. Git)\nprovider = "postgresql"\n' > prisma/migrations/migration_lock.toml
echo "Created $dir. Commit prisma/migrations."
